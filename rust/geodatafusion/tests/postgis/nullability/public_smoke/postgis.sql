SELECT ST_X(ST_StartPoint(ST_GeomFromText($1))) IS NULL AS x_is_null,
       ST_Y(ST_StartPoint(ST_GeomFromText($1))) AS y_value,
       ST_Z(ST_StartPoint(ST_GeomFromText($1))) IS NULL AS z_is_null,
       ST_M(ST_StartPoint(ST_GeomFromText($1))) IS NULL AS m_is_null,
       ST_IsEmpty(ST_GeomFromText($1)) AS is_empty,
       (ST_GeometryType(ST_GeomFromText($1)) = 'ST_LineString') AS is_linestring,
       ST_ForceCollection(ST_GeomFromText($1)) IS NULL AS force_collection_is_null,
       ST_IsEmpty(ST_ForceCollection(ST_GeomFromText($1))) AS force_collection_is_empty,
       ST_Multi(ST_GeomFromText($1)) IS NULL AS multi_is_null,
       ST_IsEmpty(ST_Multi(ST_GeomFromText($1))) AS multi_is_empty,
       ST_CollectionExtract(ST_GeomFromText($1)) IS NULL AS extract_default_is_null,
       ST_CollectionExtract(ST_GeomFromText($1), 1) IS NULL AS extract_point_is_null,
       ST_IsEmpty(ST_CollectionExtract(ST_GeomFromText($1), 1)) AS extract_point_is_empty,
       ST_CollectionHomogenize(ST_GeomFromText($1)) IS NULL AS homogenize_is_null,
       ST_Force3DM(ST_GeomFromText($1), $3) IS NULL AS force3dm_is_null,
       ST_Force4D(ST_GeomFromText($1), $3, $3) IS NULL AS force4d_is_null,
       ST_Contains(ST_GeomFromText($1), ST_GeomFromText($2)) AS contains_value,
       ST_Intersects(ST_GeomFromText($1), ST_GeomFromText($2)) AS intersects_value,
       ST_Relate(ST_GeomFromText($1), ST_GeomFromText($2)) IS NULL AS relate_is_null,
       ST_ContainsProperly(ST_GeomFromText($1), ST_GeomFromText($2)) AS contains_properly_value,
       ST_Buffer(ST_GeomFromText($1), $3) IS NULL AS buffer_is_null,
       ST_BuildArea(ST_GeomFromText($1)) IS NULL AS build_area_is_null,
       ST_LineMerge(ST_GeomFromText($1)) IS NULL AS line_merge_is_null,
       ST_OffsetCurve(ST_GeomFromText($1), $3, '') IS NULL AS offset_curve_is_null,
       ST_ReducePrecision(ST_GeomFromText($1), $3) IS NULL AS reduce_precision_is_null,
       ST_SharedPaths(ST_Force2D(ST_GeomFromText($1)), ST_Force2D(ST_GeomFromText($2))) IS NULL AS shared_paths_is_null,
       ST_TriangulatePolygon(ST_GeomFromText($1)) IS NULL AS triangulate_is_null,
       (SELECT ST_XMin(ST_Extent(ST_GeomFromText($1)))) AS extent_xmin,
       (SELECT ST_ZMax(ST_3DExtent(ST_GeomFromText($1)))) AS extent_3d_zmax
